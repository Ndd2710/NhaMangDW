CREATE   VIEW rpt.vw_DoiSoat_TonKho AS
SELECT o.MaSanPhamNghiepVu,o.MaKhoHangNghiepVu,d.Ngay,o.SoLuongDauKy,
 COALESCE((SELECT SUM(f.SoLuongMua) FROM dbo.Fact_MuaHang f JOIN dbo.Dim_SanPham p ON p.SanPhamID=f.SanPhamID WHERE p.MaSanPhamNghiepVu=o.MaSanPhamNghiepVu AND f.KhoHangID=w.KhoHangID AND f.ThoiGianID<=d.ThoiGianID),0) SoLuongNhap,
 COALESCE((SELECT SUM(f.SoLuongBan) FROM dbo.Fact_BanHang f JOIN dbo.Dim_SanPham p ON p.SanPhamID=f.SanPhamID WHERE p.MaSanPhamNghiepVu=o.MaSanPhamNghiepVu AND f.KhoHangID=w.KhoHangID AND f.ThoiGianID<=d.ThoiGianID),0) SoLuongXuat,
 i.SoLuongTon SoLuongCuoiKy
FROM wms.TonKho_DauKy o JOIN dbo.Dim_KhoHang w ON w.MaKhoHangNghiepVu=o.MaKhoHangNghiepVu CROSS JOIN dbo.Dim_ThoiGian d
LEFT JOIN dbo.Dim_SanPham p ON p.MaSanPhamNghiepVu=o.MaSanPhamNghiepVu AND d.Ngay>=p.NgayHieuLuc AND d.Ngay<p.NgayHetHieuLuc
LEFT JOIN dbo.Fact_TonKho i ON i.SanPhamID=p.SanPhamID AND i.KhoHangID=w.KhoHangID AND i.ThoiGianID=d.ThoiGianID
WHERE d.Ngay>o.NgayChotDauKy
 AND d.Ngay<=(SELECT MAX(TRY_CONVERT(date,NgayGoc,103)) FROM etl.vw_GiaoDich_Nguon);
GO
