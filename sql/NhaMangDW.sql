   WHERE NOT EXISTS(SELECT 1 FROM etl.DoiChieu_Ma m WHERE m.LoaiMa='THUE_BAO_OLTP' AND m.MaCu=s.MaThueBao)
   AND NOT EXISTS(SELECT 1 FROM etl.DoiChieu_Ma m WHERE m.LoaiMa='THUE_BAO_OLTP' AND m.MaMoi=s.MaThueBao AND m.MaCu<>s.MaThueBao)
   AND (d.MaThueBao IS NULL OR (d.NgayDangKy=s.NgayDangKy AND d.LoaiKhachHang=s.LoaiKhachHang AND EXISTS(
