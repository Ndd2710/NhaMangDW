   SELECT @dich,@ten,@loai,@dv,CASE WHEN @loai='THOAI' THEN @gia ELSE 0 END,CASE WHEN @loai='DATA' THEN @gia ELSE 0 END,0,0,0
   WHERE NOT EXISTS(SELECT 1 FROM cuoc.DanhMuc_DichVu WHERE MaDichVu=@dich);
   SET @goi+=@@ROWCOUNT;
   FETCH NEXT FROM c INTO @ma,@ten,@loai,@dv,@gia;
  END;
  CLOSE c;DEALLOCATE c;

  IF EXISTS(SELECT 1 FROM NhaMangOLTP.dbo.NhaMang WHERE MaNhaMang NOT IN('NM003','NM004','NM005'))
   THROW 56606,N'Nguồn phải giữ đúng ba nhà mạng đã thống nhất.',1;
