GO
CREATE   VIEW rpt.vw_BanHang_Thang AS SELECT MaThang,NhomSanPham,SUM(SoLuongBan) SoLuongBan,SUM(DoanhThu) DoanhThu FROM rpt.vw_BanHang_Ngay GROUP BY MaThang,NhomSanPham;
