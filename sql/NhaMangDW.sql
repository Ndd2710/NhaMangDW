  WHILE @@FETCH_STATUS=0
  BEGIN
   SET @dich=NULL;
   SELECT @dich=MaMoi FROM etl.DoiChieu_Ma WHERE LoaiMa='GOI_OLTP' AND MaCu=@ma;
   IF @dich IS NULL
   BEGIN
    SET @dich=@ma;
    -- Cùng mã nhưng khác giá/phí/tên là hai biểu giá: cấp mã DW mới, không sửa lịch sử.
    IF EXISTS(SELECT 1 FROM cuoc.DanhMuc_DichVu WHERE MaDichVu=@ma AND
     (TenGoiCuoc<>@ten OR LoaiDichVu<>@loai OR DonViTinh<>@dv OR DonGiaPhut<>CASE WHEN @loai='THOAI' THEN @gia ELSE 0 END
       OR DonGiaMB<>CASE WHEN @loai='DATA' THEN @gia ELSE 0 END OR PhiMoiPhut<>0 OR PhiMoiMB<>0 OR PhiMoiBanGhi<>0))
     OR EXISTS(SELECT 1 FROM etl.DoiChieu_Ma WHERE LoaiMa='GOI_OLTP' AND MaMoi=@ma AND MaCu<>@ma)
     OR (EXISTS(SELECT 1 FROM cuoc.DanhMuc_DichVu WHERE MaDichVu=@ma) AND NOT EXISTS(SELECT 1 FROM NhaMangOLTP.dbo.DoiChieu_Ma a JOIN etl.DoiChieu_Ma b ON b.LoaiMa='GOI_CUOC' AND b.MaCu=a.MaCu WHERE a.LoaiMa='GOI_CUOC' AND a.MaMoi=@ma AND b.MaMoi=@ma))
