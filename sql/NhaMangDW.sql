     WHERE a.LoaiMa='THUE_BAO' AND a.MaMoi=s.MaThueBao AND b.MaMoi=s.MaThueBao)));
  DECLARE @maTB varchar(30),@dichTB varchar(30),@maxTB int;
  DECLARE t CURSOR LOCAL FAST_FORWARD FOR SELECT MaThueBao FROM #ThueBao s
   WHERE NOT EXISTS(SELECT 1 FROM etl.DoiChieu_Ma m WHERE m.LoaiMa='THUE_BAO_OLTP' AND m.MaCu=s.MaThueBao) ORDER BY MaThueBao;
  OPEN t;FETCH NEXT FROM t INTO @maTB;
