CREATE   PROCEDURE etl.usp_TrichCuoc_OLTP @GiaLapLoi bit=0 AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 DECLARE @k int,@id bigint,@doc bigint=0,@trich int=0,@goi int=0,@tb int=0,@ngay int=0;
 EXEC @k=sys.sp_getapplock @Resource='NhaMangDW.ETL',@LockMode='Exclusive',@LockOwner='Session',@LockTimeout=0;
 IF @k<0 THROW 56601,N'Đang có tác vụ ETL khác; hãy chờ hoàn tất.',1;
 BEGIN TRY
  INSERT etl.NhatKy_TrichOLTP(TrangThai) VALUES('RUNNING');SET @id=SCOPE_IDENTITY();
  BEGIN TRAN;
  -- Chụp tập giao dịch trước rồi mới đọc danh mục cha. Không lọc ngày hoặc tiền tố YC.
  SELECT * INTO #Nguon FROM NhaMangOLTP.rpt.vw_NguonCuoc_ETL;
  CREATE UNIQUE CLUSTERED INDEX IX_Nguon_MaSuDung ON #Nguon(MaSuDung);
  SELECT @doc=COUNT_BIG(*) FROM #Nguon;
  IF EXISTS(SELECT 1 FROM #Nguon WHERE NgayNghiepVu<'20000101' OR NgayNghiepVu>'20991231')
   THROW 56602,N'Ngày nguồn ngoài khoảng lịch hỗ trợ 2000–2099.',1;
  IF EXISTS(SELECT 1 FROM #Nguon s JOIN NhaMangOLTP.dbo.GoiCuoc g ON g.MaGoiCuoc=s.MaGoiCuoc
   WHERE s.LoaiDichVu<>g.LoaiDichVu OR s.DonGiaPhut<>CASE WHEN g.LoaiDichVu='THOAI' THEN g.DonGia ELSE 0 END
    OR s.DonGiaMB<>CASE WHEN g.LoaiDichVu='DATA' THEN g.DonGia ELSE 0 END)
   THROW 56603,N'Giá đã chụp của giao dịch khác danh mục; cần mã phiên bản gói riêng.',1;

  DECLARE @ma varchar(30),@ten nvarchar(100),@loai varchar(10),@dv varchar(10),@gia decimal(18,2),@dich varchar(20),@max int;
