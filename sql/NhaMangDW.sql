CREATE   PROCEDURE rpt.usp_DoiChieu_BanHang_TonKho @NgayDauThang date='20261001' AS
BEGIN
 SET NOCOUNT ON;
 IF DAY(@NgayDauThang)<>1 THROW 51003,N'Ngày đầu tháng phải là ngày 1',1;
 DECLARE @NgayCuoiThang date=EOMONTH(@NgayDauThang),@ThoiGianID int=CONVERT(int,CONVERT(char(8),EOMONTH(@NgayDauThang),112));
 IF (SELECT COUNT(*) FROM dbo.Fact_TonKho WHERE ThoiGianID=@ThoiGianID)<>(SELECT COUNT(*) FROM wms.TonKho_DauKy) THROW 51004,N'Chưa đủ dữ liệu chốt tồn đồng bộ cuối kỳ',1;
 ;WITH b AS(SELECT p.NhomSanPham,SUM(f.SoLuongBan) SoLuongBan FROM dbo.Fact_BanHang f JOIN dbo.Dim_ThoiGian d ON f.ThoiGianID=d.ThoiGianID JOIN dbo.Dim_SanPham p ON p.SanPhamID=f.SanPhamID WHERE d.Ngay>=@NgayDauThang AND d.Ngay<=@NgayCuoiThang GROUP BY p.NhomSanPham),
 t AS(SELECT p.NhomSanPham,SUM(f.SoLuongTon) SoLuongTon FROM dbo.Fact_TonKho f JOIN dbo.Dim_SanPham p ON f.SanPhamID=p.SanPhamID WHERE f.ThoiGianID=@ThoiGianID GROUP BY p.NhomSanPham)
 SELECT COALESCE(b.NhomSanPham,t.NhomSanPham) NhomSanPham,COALESCE(b.SoLuongBan,0) SoLuongBan,t.SoLuongTon,@NgayCuoiThang NgayChot FROM b FULL OUTER JOIN t ON b.NhomSanPham=t.NhomSanPham ORDER BY NhomSanPham;
END;
GO
