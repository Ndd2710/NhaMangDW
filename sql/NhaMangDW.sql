      SELECT MaDichVu Ma FROM cuoc.DanhMuc_DichVu UNION ALL SELECT MaGoiCuoc FROM NhaMangOLTP.dbo.GoiCuoc
      UNION ALL SELECT MaMoi FROM etl.DoiChieu_Ma WHERE LoaiMa='GOI_OLTP') a
      WHERE LEN(Ma)=5 AND LEFT(Ma,2)='GC' AND RIGHT(Ma,3) NOT LIKE '%[^0-9]%';
     IF ISNULL(@max,0)>=999 THROW 56604,N'Đã hết dải mã GC ba chữ số; cần mở rộng quy tắc mã có kiểm soát.',1;
     SET @dich='GC'+RIGHT('000'+CONVERT(varchar(10),ISNULL(@max,0)+1),3);
    END;
    INSERT etl.DoiChieu_Ma(LoaiMa,MaCu,MaMoi) VALUES('GOI_OLTP',@ma,@dich);
   END;
   IF EXISTS(SELECT 1 FROM cuoc.DanhMuc_DichVu WHERE MaDichVu=@dich AND
    (TenGoiCuoc<>@ten OR LoaiDichVu<>@loai OR DonViTinh<>@dv OR DonGiaPhut<>CASE WHEN @loai='THOAI' THEN @gia ELSE 0 END
     OR DonGiaMB<>CASE WHEN @loai='DATA' THEN @gia ELSE 0 END OR PhiMoiPhut<>0 OR PhiMoiMB<>0 OR PhiMoiBanGhi<>0))
    THROW 56605,N'Ánh xạ gói OLTP đã có nhưng nội dung thay đổi; không ghi đè biểu giá.',1;
