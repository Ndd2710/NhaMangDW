  IF EXISTS(SELECT 1 FROM #ThueBao s JOIN etl.DoiChieu_Ma m ON m.LoaiMa='THUE_BAO_OLTP' AND m.MaCu=s.MaThueBao
   JOIN cuoc.DanhMuc_ThueBao d ON d.MaThueBao=m.MaMoi WHERE d.NgayDangKy<>s.NgayDangKy OR d.LoaiKhachHang<>s.LoaiKhachHang)
