  SET @tb=@@ROWCOUNT;

  -- Tạo đủ ngày trong các tháng có giao dịch, kể cả tháng mới hoặc bản ghi đến muộn.
  ;WITH thang AS(SELECT DISTINCT DATEFROMPARTS(YEAR(NgayNghiepVu),MONTH(NgayNghiepVu),1) Dau FROM #Nguon),
