CREATE   PROCEDURE dbo.usp_KhoaGiaoDich @ThueBaoID int=NULL,@MaYeuCau varchar(60)=NULL AS
BEGIN
 SET NOCOUNT ON;
 IF @@TRANCOUNT=0 THROW 56100,N'Khóa nghiệp vụ phải nằm trong transaction.',1;
 DECLARE @r int,@resource nvarchar(255);
 IF @MaYeuCau IS NOT NULL
 BEGIN
  IF LEN(LTRIM(RTRIM(@MaYeuCau)))=0 THROW 56101,N'Mã yêu cầu không được trống.',1;
  SET @resource=N'NhaMangOLTP.YeuCau.'+@MaYeuCau;
  EXEC @r=sys.sp_getapplock @Resource=@resource,@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
  IF @r<0 THROW 56102,N'Đang xử lý yêu cầu khác. Vui lòng thử lại.',1;
 END;
 IF @ThueBaoID IS NOT NULL
 BEGIN
  SET @resource=N'NhaMangOLTP.ThueBao.'+CONVERT(nvarchar(20),@ThueBaoID);
  EXEC @r=sys.sp_getapplock @Resource=@resource,@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=10000;
  IF @r<0 THROW 56102,N'Đang xử lý thuê bao. Vui lòng thử lại.',1;
 END;
END;
GO
CREATE   PROCEDURE dbo.usp_TaoMaYeuCau @MaYeuCau varchar(60)=NULL OUTPUT AS
BEGIN
 SET NOCOUNT ON;
 DECLARE @n bigint=NEXT VALUE FOR dbo.Seq_YeuCau;
 IF @n>999999999999 THROW 56504,N'Đã hết khoảng mã yêu cầu.',1;
 SET @MaYeuCau='YC'+RIGHT('000000000000'+CONVERT(varchar(20),@n),12);
 SELECT @MaYeuCau MaYeuCau;
END;
GO
