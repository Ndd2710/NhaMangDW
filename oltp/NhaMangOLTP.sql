CREATE   PROCEDURE dbo.usp_DangKyGoiCuoc
 @MaYeuCau varchar(60),@ThueBaoID int,@GoiCuocID int,@NgayBatDau datetime2(0),@NgayKetThuc datetime2(0)=NULL AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 SET @MaYeuCau=UPPER(dbo.fn_MaChuan('YC_DK',@MaYeuCau));
 IF @MaYeuCau IS NULL OR LEN(@MaYeuCau)<>14 OR LEFT(@MaYeuCau,2)<>'YC' OR RIGHT(@MaYeuCau,12) LIKE '%[^0-9]%'
  THROW 56506,N'Mã yêu cầu phải dạng YC + 12 chữ số; dùng usp_TaoMaYeuCau và giữ mã đó khi gửi lại.',1;

 BEGIN TRY BEGIN TRAN;
 EXEC dbo.usp_KhoaGiaoDich @ThueBaoID,@MaYeuCau;
 IF EXISTS(SELECT 1 FROM dbo.DangKyGoiCuoc WHERE MaYeuCau=@MaYeuCau)
 BEGIN
  IF NOT EXISTS(SELECT 1 FROM dbo.DangKyGoiCuoc WHERE MaYeuCau=@MaYeuCau AND ThueBaoID=@ThueBaoID AND GoiCuocID=@GoiCuocID AND NgayBatDau=@NgayBatDau AND ISNULL(NgayKetThucDuKien,'99991231')=ISNULL(@NgayKetThuc,'99991231')) THROW 56104,N'Mã yêu cầu đã dùng với dữ liệu khác.',1;
  SELECT DangKyID ID FROM dbo.DangKyGoiCuoc WHERE MaYeuCau=@MaYeuCau;COMMIT;RETURN;
 END;

 IF EXISTS(SELECT 1 FROM dbo.DangKyGoiCuoc WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.CuocGoi WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.PhienInternet WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.NapTien WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.HoaDon WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.ThanhToan WHERE MaYeuCau=@MaYeuCau) THROW 56505,N'Mã yêu cầu đã thuộc nghiệp vụ khác; cần mã mới.',1;
