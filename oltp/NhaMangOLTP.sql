CREATE   PROCEDURE dbo.usp_TaoThueBao

 @MaThueBao varchar(30),@SoThueBao varchar(25),@KhachHangID int,@NhaMangID int,@KhuVucID int,

 @LoaiThueBao varchar(10),@NgayDangKy datetime2(0) AS

BEGIN

 SET NOCOUNT ON;SET XACT_ABORT ON;

 SET @MaThueBao=dbo.fn_MaChuan('THUE_BAO',@MaThueBao);

 IF @MaThueBao IS NULL OR LEN(@MaThueBao)<>8 OR LEFT(@MaThueBao,2)<>'TB' OR RIGHT(@MaThueBao,6) LIKE '%[^0-9]%'

  THROW 56401,N'Mã mới phải theo dạng TB000000; mã cũ đã ánh xạ vẫn được chấp nhận khi gửi lại.',1;

 SET @SoThueBao=dbo.fn_MaChuan('SO_THUE_BAO',@SoThueBao);
 SET @NhaMangID=TRY_CONVERT(int,dbo.fn_MaChuan('NHA_MANG_ID_OLTP',CONVERT(varchar(20),@NhaMangID)));



 IF LEN(LTRIM(RTRIM(@MaThueBao)))=0 OR LEN(LTRIM(RTRIM(@SoThueBao)))=0 THROW 56103,N'Mã và số thuê bao không được trống.',1;

 BEGIN TRY BEGIN TRAN;

 DECLARE @yc varchar(60)='TB:'+@MaThueBao;

 EXEC dbo.usp_KhoaGiaoDich @MaYeuCau=@yc;

 IF EXISTS(SELECT 1 FROM dbo.ThueBao WHERE MaThueBao=@MaThueBao AND

  (SoThueBao<>@SoThueBao OR KhachHangID<>@KhachHangID OR NhaMangID<>@NhaMangID OR KhuVucID<>@KhuVucID OR LoaiThueBao<>@LoaiThueBao OR NgayDangKy<>@NgayDangKy)) THROW 56104,N'Mã thuê bao đã có với nội dung khác.',1;

 IF NOT EXISTS(SELECT 1 FROM dbo.ThueBao WHERE MaThueBao=@MaThueBao)

  INSERT dbo.ThueBao(MaThueBao,SoThueBao,KhachHangID,NhaMangID,KhuVucID,LoaiThueBao,NgayDangKy)

  VALUES(@MaThueBao,@SoThueBao,@KhachHangID,@NhaMangID,@KhuVucID,@LoaiThueBao,@NgayDangKy);

 SELECT ThueBaoID ID FROM dbo.ThueBao WHERE MaThueBao=@MaThueBao;

 COMMIT;END TRY BEGIN CATCH IF @@TRANCOUNT>0 ROLLBACK;THROW;END CATCH;

END;
GO
CREATE   PROCEDURE dbo.usp_ThanhToanHoaDon
 @MaYeuCau varchar(60),@HoaDonID bigint,@SoTien decimal(18,2),@ThoiDiem datetime2(0),@PhuongThuc varchar(20) AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 SET @MaYeuCau=UPPER(dbo.fn_MaChuan('YC_THANH_TOAN',@MaYeuCau));
 IF @MaYeuCau IS NULL OR LEN(@MaYeuCau)<>14 OR LEFT(@MaYeuCau,2)<>'YC' OR RIGHT(@MaYeuCau,12) LIKE '%[^0-9]%'
  THROW 56506,N'Mã yêu cầu phải dạng YC + 12 chữ số; dùng usp_TaoMaYeuCau và giữ mã đó khi gửi lại.',1;

 DECLARE @tb int;SELECT @tb=ThueBaoID FROM dbo.HoaDon WHERE HoaDonID=@HoaDonID;
 IF @tb IS NULL THROW 56216,N'Hóa đơn không tồn tại.',1;
 BEGIN TRY BEGIN TRAN;
 EXEC dbo.usp_KhoaGiaoDich @tb,@MaYeuCau;
 IF EXISTS(SELECT 1 FROM dbo.ThanhToan WHERE MaYeuCau=@MaYeuCau)
 BEGIN
  IF NOT EXISTS(SELECT 1 FROM dbo.ThanhToan WHERE MaYeuCau=@MaYeuCau AND HoaDonID=@HoaDonID AND SoTien=@SoTien AND ThoiDiem=@ThoiDiem AND PhuongThuc=@PhuongThuc) THROW 56104,N'Mã yêu cầu thanh toán đã dùng với dữ liệu khác.',1;
  SELECT ThanhToanID ID FROM dbo.ThanhToan WHERE MaYeuCau=@MaYeuCau;COMMIT;RETURN;
 END;

 IF EXISTS(SELECT 1 FROM dbo.DangKyGoiCuoc WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.CuocGoi WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.PhienInternet WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.NapTien WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.HoaDon WHERE MaYeuCau=@MaYeuCau) OR EXISTS(SELECT 1 FROM dbo.ThanhToan WHERE MaYeuCau=@MaYeuCau) THROW 56505,N'Mã yêu cầu đã thuộc nghiệp vụ khác; cần mã mới.',1;
 IF @SoTien<=0 THROW 56217,N'Số tiền thanh toán phải lớn hơn 0.',1;
 IF NOT EXISTS(SELECT 1 FROM dbo.HoaDon WHERE HoaDonID=@HoaDonID AND TongTien-SoTienDaThanhToan>=@SoTien AND NgayLap<=@ThoiDiem) THROW 56218,N'Thanh toán vượt số còn nợ hoặc trước ngày lập hóa đơn.',1;
 INSERT dbo.ThanhToan(MaYeuCau,HoaDonID,SoTien,ThoiDiem,PhuongThuc) VALUES(@MaYeuCau,@HoaDonID,@SoTien,@ThoiDiem,@PhuongThuc);
 DECLARE @id bigint=SCOPE_IDENTITY();
 UPDATE dbo.HoaDon SET SoTienDaThanhToan=SoTienDaThanhToan+@SoTien WHERE HoaDonID=@HoaDonID;
 SELECT @id ID;
 COMMIT;END TRY BEGIN CATCH IF @@TRANCOUNT>0 ROLLBACK;THROW;END CATCH;
END;
GO
